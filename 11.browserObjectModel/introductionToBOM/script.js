/* A. INTRODUCTION TO BROWSER OBJECT MODEL
  1. The Browser Object Model (BOM) allows JavaScript to "talk to" the browser. 
  2. BOM consists of various objects that represent different aspects of the browser environment.
  3. BOM objects are not tied to specific websites or web pages. They exist at the browser level and are 
     accessible to JavaScript code running within any web page loaded in the browser.
  4. During Browser Initialization, mostly BOM Objects are created in the Heap Memory by the Browser 
     Rendering Engine(Blink in Chrome).
  5. BOM objects are not part of JavaScript language. They are a part of the browser environment.
  6. Here we will discuss the BOM objects like- window, screen, location, history, navigator, popups, 
     timing and cookies.
  7. Unlike the DOM, where elements are arranged in a hierarchical tree structure, the BOM objects exist 
     independently, and there is no defined parent-child relationship between them. They simply provide 
     access to different browser-specific features and information. */


