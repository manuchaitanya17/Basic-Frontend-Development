//CHAPTER-1 INTRODUCTION TO DOCUMENT OBJECT MODEL

/* A. DOCUMENT OBJECT MODEL
  1. When an HTML Document is parsed by the Browser, the Browser's Rendering Engine creates the
     DOM objects in memory based on the structure and content of the HTML document. These DOM 
     Objects represent Elements, Attributes, Text Nodes, and other entities defined in the HTML. 
     
  2. Once the DOM objects are created, developers can use the DOM API to access, modify, add, 
     or remove these objects dynamically. 
     
  3. The BOM and DOM are not part of the Core JavaScript Language Specification, but rather
     are provided by the Web Browser Environment in which JavaScript is running.
     
  4. The W3C DOM standard is separated into THREE different parts:
     - Core DOM - standard model for all document types
     - XML DOM - standard model for XML documents
     - HTML DOM - standard model for HTML documents */




/* B. WHAT CAN JAVASCRIPT DO WITH DOM OBJECTS
  1. JavaScript allows us to ACCESS, MODIFY, ADD, OR REMOVE Element Objects.
  
  2. JavaScript allows us to ACCESS, MODIFY, ADD, OR REMOVE Element's Attributes.
  
  3. JavaScript allows us to ACCESS, MODIFY, ADD, OR REMOVE Element's Style.
  
  4. JavaScript can REACT to all existing HTML Events in the page.
  
  5. JavaScript can create new HTML Events in the page. */